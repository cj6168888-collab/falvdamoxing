def search_legal_knowledge(query: str, top_k: int = 5) -> list:
    """
    基于关键词搜索法律知识

    Args:
        query: 查询文本
        user_position: 用户立场（有利/不利）

    Returns:
        相关法律条文列表
    """
    query_lower = query.lower()
    query_keywords = query_lower.replace("，", ",").replace("。", ".").split()

    # 计算每个条文的匹配分数
    scored_results = []

    for key, law in LEGAL_KNOWLEDGE_BASE.items():
        score = 0
        matched_keywords = []

        # 检查关键词匹配
        for keyword in law["keywords"]:
            if keyword.lower() in query_lower:
                score += 2
                matched_keywords.append(keyword)

        # 检查全文匹配
        if law["content"].lower() in query_lower:
            score += 5

        if score > 0:
            scored_results.append({
                "key": key,
                "score": score,
                "matched_keywords": matched_keywords,
                **law
            })

    # 按分数排序
    scored_results.sort(key=lambda x: x["score"], reverse=True)

    # 返回前 top_k 个结果
    return scored_results[:top_k]


def get_law_by_article(title: str, article: str) -> dict:
    """
    根据法律名称和条文号获取具体法律条文
    """
    for key, law in LEGAL_KNOWLEDGE_BASE.items():
        if law["title"] == title and law["article"] == article:
            return law
    return None


def verify_citation(title: str, article: str) -> dict:
    """
    验证法律引用是否有效
    返回: (is_valid, law_info, warning)
    """
    law = get_law_by_article(title, article)

    if law:
        if law["is_valid"]:
            return {
                "is_valid": True,
                "law": law,
                "warning": None
            }
        else:
            return {
                "is_valid": False,
                "law": None,
                "warning": f"《{title}》{article}已失效或已被废止"
            }
    else:
        return {
            "is_valid": False,
            "law": None,
            "warning": f"《{title}》{article}不在知识库中，请核实法律名称和条文编号"
        }
